while True:
    num = int(input("Enter a number (1-7): "))

    if num == 1:
        print("Monday")
    if num == 2:
        print("Tuesday")
    if num == 3:
        print("Wednesday")
    if num == 4:
        print("Thursday")
    if num == 5:
        print("Friday")
    if num == 6:
        print("Saturday")
    if num == 7:
        print("Sunday")
    else:
        print("Invalid input. Please enter a number between 1 and 7.\n")